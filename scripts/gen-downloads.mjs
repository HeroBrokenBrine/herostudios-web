// Regenerates src/data/downloads.js from public/downloads/<slug>/.
// Run: node scripts/gen-downloads.mjs
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const downloadsDir = join(root, "public", "downloads");
const outFile = join(root, "src", "data", "downloads.js");

const labels = {
  "hero-client": "1.21 (Fabric)",
};

const dptRe = /^Hero Studios\s+(.+?)\s+(\d\S+)$/;
const mcRe = /(1\.\d{1,2}(?:\.\d{1,2})?|26\.\d(?:\.\d{1,2})?)/;

function deriveLabel(slug, file) {
  if (labels[slug]) return labels[slug];
  const base = file.replace(/\.(jar|zip|mcpack)$/i, "");
  const isSources = /sources/i.test(base);
  if (slug.startsWith("dpt")) {
    const m = base.match(dptRe);
    if (m) {
      let label = `${m[1]} - ${m[2]}`;
      if (isSources) label += " (sources)";
      return label;
    }
  }
  const m = base.match(mcRe);
  let label = m ? m[1] : base;
  if (isSources) label += " (sources)";
  return label;
}

const manifest = {};
for (const slug of readdirSync(downloadsDir)) {
  const dir = join(downloadsDir, slug);
  if (!statSync(dir).isDirectory()) continue;
  const files = readdirSync(dir)
    .filter((f) => /\.(jar|zip|mcpack)$/i.test(f))
    .filter((f) => !/-sources\.jar$/i.test(f) && !/-dev\.jar$/i.test(f))
    .sort();
  manifest[slug] = {
    files: files.map((f) => {
      const buf = readFileSync(join(dir, f));
      return {
        file: f,
        label: deriveLabel(slug, f),
        size: buf.length,
        sha256: createHash("sha256").update(buf).digest("hex"),
      };
    }),
  };
}

const js = `// AUTO-GENERATED by scripts/gen-downloads.mjs — do not edit by hand.\n// Regenerate after updating release artifacts: node scripts/gen-downloads.mjs\nexport const downloads = ${JSON.stringify(manifest, null, 2)};\n`;
writeFileSync(outFile, js, "utf8");
console.log(`Wrote ${outFile}`);
for (const [slug, d] of Object.entries(manifest)) {
  console.log(`${slug}: ${d.files.length} file(s), ${(d.files.reduce((a, f) => a + f.size, 0) / 1048576).toFixed(1)} MB`);
}
